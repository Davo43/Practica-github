#Realiza un programa que introduciendo el valor del lado de un cuadrado nos devuelva por pantalla en el area y el perimetro. 
numero1 = float(input("Introduce el primer numero: "))
Perimetro = numero1 * 4
area = numero1 ** 2
print(f"El perimetro del cuadrado es: {Perimetro:.0f}")
print(f"El area del cuadrado es: {area:.0f}")