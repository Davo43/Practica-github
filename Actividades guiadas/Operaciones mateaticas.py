a=float(input("Introduce el primer numero: "))
b=float(input("Introduce el segundo numero: "))
suma= a + b
resta= a - b
multiplicación= a * b
division= a / b
potencia= a ** b
division_entera= a // b
resto= a % b
print(f"La suma es {suma:.0f}")
print(f"La resta es {resta:.0f}")
print(f"La multiplicación es {multiplicación:.0f}")
print(f"La división es {division:.2f}")
print(f"La potencia es {potencia:.0f}")
print(f"La división entera es {division_entera:.0f}")
print(f"El resto es {resto:.0f}")

